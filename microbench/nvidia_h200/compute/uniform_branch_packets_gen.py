"""Generate independent uniform forward-guard packets;no operator code."""
from pathlib import Path
import struct


def fbits(x):
    return '0f' + struct.pack('>f', float(x)).hex().upper()


def packet(guards, skip, guarded):
    lines = ['{', f'.reg .f32 x<{guards}>;', f'.reg .u32 u<{guards}>,lane,h,tmp,m;',
        '.reg .pred mode,drop,bad;', 'add.u32 tmp,%9,31;', 'and.b32 lane,%6,tmp;', 'mov.u32 h,0;']
    for i in range(guards):
        lines += [f'ld.volatile.global.u32 u{i},[%8+{i*4}];',
            f'add.rn.f32 x{i},%5,{fbits(i*.25)};', f'xor.b32 h,h,u{i};']
    lines += ['and.b32 h,h,%9;', 'setp.ne.u32 bad,h,0;', '@bad trap;',
        'add.u32 m,%4,h;', 'setp.eq.u32 mode,m,1;', 'bar.sync 1,%10;',
        'mov.u64 %2,%%globaltimer;', 'mov.u64 %0,%%clock64;']
    for i in range(guards):
        qualifier = '@mode ' if guarded else ''
        lines += [f'setp.gt.s32 drop,lane,{127-4*i};',
            f'{qualifier}selp.f32 x{i},{fbits(float("-inf"))},x{i},drop;']
        if guarded:
            lines += [f'@mode bra.uni NEXT_{i};']
            lines += [f'mad.lo.u32 u{i},u{i},u{i},1013904223;' for _ in range(skip)]
            lines += [f'setp.gt.u32 drop,u{i},127;',
                f'selp.f32 x{i},{fbits(float("-inf"))},x{i},drop;', f'NEXT_{i}:']
    lines += ['mov.u64 %1,%%clock64;', 'mov.u64 %3,%%globaltimer;']
    for i in range(guards):
        lines += [f'st.volatile.global.f32 [%7+{i*4}],x{i};',
            f'st.volatile.global.u32 [%7+{(guards+i)*4}],u{i};']
    lines += ['}']
    literal = '\n'.join('        "' + line.replace('\\', '\\\\').replace('"','\\"') + '\\n"' for line in lines)
    return f'''template<> __device__ __forceinline__ Stamp packet<{guards},{skip},{str(guarded).lower()}>(
        unsigned mode,unsigned tid,const unsigned* input,unsigned* output,unsigned zero,int count) {{
    Stamp s;
    asm volatile(
{literal}
        : "=l"(s.c0),"=l"(s.c1),"=l"(s.n0),"=l"(s.n1)
        : "r"(mode),"f"(float(tid+1)),"r"(tid),"l"(output),"l"(input),"r"(zero),"r"(count)
        : "memory");
    return s;
}}
'''


def main():
    out = Path(__file__).with_name('uniform_branch_packets.cuh')
    text = '// Generated by uniform_branch_packets_gen.py;no production program.\n'
    text += 'template<int Guards,int Skip,bool Guarded> __device__ Stamp packet(unsigned,unsigned,const unsigned*,unsigned*,unsigned,int);\n'
    for guards in (16,32,48,64):
        text += packet(guards,0,False)
        for skip in (8,12,16):
            text += packet(guards,skip,True)
    out.write_text(text)


if __name__ == '__main__':
    main()
