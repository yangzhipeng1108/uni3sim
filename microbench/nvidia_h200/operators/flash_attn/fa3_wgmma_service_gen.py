#!/usr/bin/env python3
"""Generate fa3_wgmma_service.cu (H200 sm_90a WGMMA service probe).

The probe isolates the Hopper warpgroup MMA (``wgmma.mma_async``) service for
the BF16 x BF16 -> FP32 instruction shapes that the pinned FlashAttention-3
source issues for MLA (vllm-flash-attention 803020a8, hopper/
mainloop_fwd_sm90_tma_gmma_ws.hpp):

  prefill (hdim 192 / hdimv 128, kBlockM 128, kBlockN 128, 2 MMA warpgroups)
    QK  m64n128k16 SS, K-major A and B, 12 k-steps per gemm
    PV  m64n128k16 RS (P in registers), MN-major V, 8 k-steps per gemm
  decode (hdim 64 / hdimv 512, kBlockM 64, kBlockN 64, LargeHeadDimV)
    QK  m64n64k16 SS, 4 k-steps;  QV m64n64k16 SS, 32 k-steps
    PV  m64n256k16 SS (WG1) / RS (WG0), MN-major V, 4 k-steps

Operand contents are irrelevant to the service (they are whatever the shared
memory holds); descriptors use the 128-byte swizzle layout the source selects
(``ss_smem_selector``) with in-bounds start/stride offsets.  Only the Python
standard library is used.  Run: ``python3 fa3_wgmma_service_gen.py > fa3_wgmma_service.cu``.
"""

SHAPES = (  # (name, n, register_a, transpose_b)
    ('ss_n64_kmajor', 64, False, 0),
    ('ss_n128_kmajor', 128, False, 0),
    ('rs_n128_mnmajor', 128, True, 1),
    ('ss_n256_mnmajor', 256, False, 1),
    ('rs_n256_mnmajor', 256, True, 1),
)
KSTEPS = (1, 2, 4, 8, 12, 32, 36)


def wgmma_function(name, n, register_a, transpose_b):
    regs = n // 2
    d_list = ', '.join(f'%{i}' for i in range(regs))
    outs = ', '.join(f'"+f"(d[{i}])' for i in range(regs))
    if register_a:
        a_ops = '{' + ', '.join(f'%{regs + i}' for i in range(4)) + '}'
        b_op = f'%{regs + 4}'
        scale = regs + 5
        ins = ('"r"(a[0]), "r"(a[1]), "r"(a[2]), "r"(a[3]), "l"(desc_b), '
               '"r"(scale_d)')
        tail = f'p, 1, 1, {transpose_b}'
        signature = ('uint32_t const (&a)[4], uint64_t desc_b')
    else:
        a_ops = f'%{regs}'
        b_op = f'%{regs + 1}'
        scale = regs + 2
        ins = '"l"(desc_a), "l"(desc_b), "r"(scale_d)'
        tail = f'p, 1, 1, 0, {transpose_b}'
        signature = 'uint64_t desc_a, uint64_t desc_b'
    return f'''
__device__ __forceinline__ void wgmma_{name}(float (&d)[{regs}], {signature}, int scale_d) {{
    asm volatile(
        "{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{scale}, 0;\\n"
        "wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 "
        "{{{d_list}}}, {a_ops}, {b_op}, {tail};\\n}}\\n"
        : {outs}
        : {ins});
}}
'''


HEADER = r'''// GENERATED by fa3_wgmma_service_gen.py -- do not edit by hand.
//
// H200 (sm_90a) WGMMA service probe for the FlashAttention-3 MLA instruction
// shapes (see the generator docstring).  One CTA per SM (large dynamic shared
// memory), 1..2 warpgroups issue a loop of ``reps`` gemms; one gemm is
// KSTEPS back-to-back wgmma.mma_async instructions into one accumulator,
// followed by wgmma.commit_group and wgmma.wait_group 0 -- the issue/retire
// pattern of flash::gemm<zero_init, wg_wait=0> in the pinned source.  The
// first warp of each warpgroup records clock64() around the loop, so the
// output is SM cycles (clock-domain independent); the runner clock-gates the
// capture at the 1980-MHz boost clock anyway.
//
// usage: fa3_wgmma_service SHAPE KSTEPS ACTIVE_WG GRID REPS
//   prints "shape,ksteps,active_wg,grid,reps,cta,wg,cycles" rows.
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>
#include <cuda_runtime.h>

#define CHECK(call) do { cudaError_t e_ = (call); if (e_ != cudaSuccess) { \
    std::fprintf(stderr, "%s:%d %s\n", __FILE__, __LINE__, cudaGetErrorString(e_)); \
    std::exit(2); } } while (0)

constexpr int kSmemBytes = 200 * 1024;

__device__ __forceinline__ uint64_t make_desc(uint32_t smem_addr, uint32_t lbo, uint32_t sbo) {
    uint64_t desc = 0;
    desc |= uint64_t((smem_addr >> 4) & 0x3FFF);
    desc |= uint64_t((lbo >> 4) & 0x3FFF) << 16;
    desc |= uint64_t((sbo >> 4) & 0x3FFF) << 32;
    desc |= uint64_t(1) << 62;  // 128-byte swizzle
    return desc;
}
__device__ __forceinline__ void wg_fence() { asm volatile("wgmma.fence.sync.aligned;\n" ::: "memory"); }
__device__ __forceinline__ void wg_commit() { asm volatile("wgmma.commit_group.sync.aligned;\n" ::: "memory"); }
__device__ __forceinline__ void wg_wait0() { asm volatile("wgmma.wait_group.sync.aligned 0;\n" ::: "memory"); }
'''

KERNEL = r'''
template <int N, bool RS, int TRANSB, int KSTEPS>
__global__ void __launch_bounds__(256, 1)
probe(int reps, int active_wg, unsigned long long* out, float* sink) {
    extern __shared__ __align__(1024) unsigned char smem[];
    const int wg = threadIdx.x / 128;
    const uint32_t base = static_cast<uint32_t>(__cvta_generic_to_shared(smem));
    float d[N / 2];
    #pragma unroll
    for (int i = 0; i < N / 2; ++i) d[i] = 0.f;
    uint32_t a[4] = {threadIdx.x * 0x00010001u, 0x3f803f80u, 0x3f003f00u, threadIdx.x};
    // A: 64 rows x K (K-major, 128B swizzle atoms of 64 elements), B after 64 KiB.
    const uint32_t a_base = base;
    const uint32_t b_base = base + 64 * 1024;
    __syncthreads();
    unsigned long long start = 0, stop = 0;
    if (wg < active_wg) {
        start = clock64();
        for (int r = 0; r < reps; ++r) {
            wg_fence();
            #pragma unroll
            for (int k = 0; k < KSTEPS; ++k) {
                const uint32_t k_off_a = (k % 4) * 32 + (k / 4) * (64 * 128);
                const uint64_t desc_b = TRANSB
                    ? make_desc(b_base + (k % 8) * 2048, 8192, 1024)
                    : make_desc(b_base + (k % 4) * 32 + ((k / 4) % 4) * (N * 128), 16, 1024);
                if constexpr (RS) {
                    WGMMA_RS(d, a, desc_b, (r | k) != 0);
                } else {
                    const uint64_t desc_a = make_desc(a_base + (k_off_a % (64 * 1024)), 16, 1024);
                    WGMMA_SS(d, desc_a, desc_b, (r | k) != 0);
                }
            }
            wg_commit();
            wg_wait0();
        }
        stop = clock64();
    }
    float acc = 0.f;
    #pragma unroll
    for (int i = 0; i < N / 2; ++i) acc += d[i];
    if (acc == 1234.5f) sink[threadIdx.x] = acc;
    if (wg < active_wg && threadIdx.x % 128 == 0) {
        out[(blockIdx.x * 2 + wg) * 2 + 0] = start;
        out[(blockIdx.x * 2 + wg) * 2 + 1] = stop;
    }
}
'''


def main():
    parts = [HEADER]
    for name, n, register_a, transpose_b in SHAPES:
        parts.append(wgmma_function(name, n, register_a, transpose_b))
    # Per-shape kernels: bind WGMMA_SS / WGMMA_RS macros to the shape function.
    for name, n, register_a, transpose_b in SHAPES:
        macro = 'WGMMA_RS' if register_a else 'WGMMA_SS'
        other = 'WGMMA_SS' if register_a else 'WGMMA_RS'
        body = KERNEL.replace('probe(', f'probe_{name}(')
        body = body.replace(f'{macro}(', f'wgmma_{name}(')
        body = body.replace(f'{other}(d, ', '/*unused*/(void)(')
        parts.append(body)
    dispatch = ['''
template <typename Kernel>
static void run(Kernel kernel, const char* shape, int ksteps, int active_wg, int grid, int reps) {
    CHECK(cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize, kSmemBytes));
    unsigned long long* out = nullptr; float* sink = nullptr;
    CHECK(cudaMalloc(&out, sizeof(unsigned long long) * grid * 4));
    CHECK(cudaMalloc(&sink, sizeof(float) * 256));
    CHECK(cudaMemset(out, 0, sizeof(unsigned long long) * grid * 4));
    kernel<<<grid, 256, kSmemBytes>>>(reps, active_wg, out, sink);  // warm-up
    CHECK(cudaGetLastError()); CHECK(cudaDeviceSynchronize());
    kernel<<<grid, 256, kSmemBytes>>>(reps, active_wg, out, sink);
    CHECK(cudaGetLastError()); CHECK(cudaDeviceSynchronize());
    std::vector<unsigned long long> host(grid * 4);
    CHECK(cudaMemcpy(host.data(), out, sizeof(unsigned long long) * grid * 4, cudaMemcpyDeviceToHost));
    std::printf("shape,ksteps,active_wg,grid,reps,cta,wg,cycles\\n");
    for (int c = 0; c < grid; ++c)
        for (int w = 0; w < active_wg; ++w)
            std::printf("%s,%d,%d,%d,%d,%d,%d,%llu\\n", shape, ksteps, active_wg, grid, reps, c, w,
                        host[(c * 2 + w) * 2 + 1] - host[(c * 2 + w) * 2 + 0]);
    CHECK(cudaFree(out)); CHECK(cudaFree(sink));
}

int main(int argc, char** argv) {
    if (argc != 6) { std::fprintf(stderr, "usage: %s SHAPE KSTEPS ACTIVE_WG GRID REPS\\n", argv[0]); return 1; }
    const char* shape = argv[1];
    const int ksteps = std::atoi(argv[2]), active_wg = std::atoi(argv[3]);
    const int grid = std::atoi(argv[4]), reps = std::atoi(argv[5]);
    if (active_wg < 1 || active_wg > 2 || grid < 1 || reps < 1) { std::fprintf(stderr, "bad args\\n"); return 1; }
''']
    for name, n, register_a, transpose_b in SHAPES:
        for k in KSTEPS:
            rs = 'true' if register_a else 'false'
            dispatch.append(
                f'    if (!std::strcmp(shape, "{name}") && ksteps == {k}) '
                f'{{ run(probe_{name}<{n}, {rs}, {transpose_b}, {k}>, shape, ksteps, active_wg, grid, reps); return 0; }}\n')
    dispatch.append('    std::fprintf(stderr, "unknown shape/ksteps\\n");\n    return 1;\n}\n')
    parts.append(''.join(dispatch))
    print(''.join(parts))


if __name__ == '__main__':
    main()
