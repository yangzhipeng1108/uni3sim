#!/bin/sh
set -eu

if [ -z "${MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHON:-}" ]; then
    echo "MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHON is required" >&2
    exit 64
fi
if [ -z "${MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHONPATH:-}" ]; then
    echo "MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHONPATH is required" >&2
    exit 64
fi
if [ -n "${PYTHONPATH:-}" ]; then
    export PYTHONPATH="${MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHONPATH}:${PYTHONPATH}"
else
    export PYTHONPATH="${MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHONPATH}"
fi
exec "${MIDLAYER_SCHEDULER_TRACE_SPAWN_PYTHON}" "$@"
